/** 注入原始下标，并按奇偶分两列用于错落瀑布流布局 */
const LIST_INDEXED: Dest[] = LIST.map((d, i) => ({ ...d, index: i }));
function splitCols(src: Dest[]): [Dest[], Dest[]] {
  const left: Dest[] = [];
  const right: Dest[] = [];
  src.forEach((d, i) => (i % 2 === 0 ? left : right).push(d));
  return [left, right];
}

function statusBarHeight(): number {
  try {
    const info: any = (wx as any).getWindowInfo
      ? (wx as any).getWindowInfo()
      : wx.getSystemInfoSync();
    return (info && info.statusBarHeight) || 44;
  } catch (e) {
    return 44;
  }
}

/** 页面 data 形状 */
interface InspirationData {
  statusBarH: number;
  bodyPad: number;
  view: 'grid' | 'plans' | 'post';
  list: Dest[];
  colL: Dest[];
  colR: Dest[];
  curDest: Dest | null;
  curPlan: TravelPlan | null;
}

Page<InspirationData>({
  data: {
    statusBarH: 44,
    bodyPad: 16,
    view: 'grid',
    list: LIST_INDEXED,
    colL: splitCols(LIST_INDEXED)[0],
    colR: splitCols(LIST_INDEXED)[1],
    curDest: null,
    curPlan: null
  },

  onLoad() {
    const sb = statusBarHeight();
    // 状态栏高度已由导航栏（内联 padding-top:statusBarH）让出，
    // 正文只需留一点间隙，不要再重复叠加状态栏高度，否则顶部会凭空出现大片空白。
    this.setData({ statusBarH: sb, bodyPad: 16 });
  },

  /** 导航栏返回：页内层级逐级回退，最外层才离开页面 */
  onBack() {
    const v = this.data.view;
    if (v === 'post') {
      this.setData({ view: 'plans', curPlan: null });
      this.scrollTop();
      return;
    }
    if (v === 'plans') {
      this.setData({ view: 'grid', curDest: null });
      this.scrollTop();
      return;
    }
    wx.navigateBack({
      delta: 1,
      fail: () => {
        wx.reLaunch({ url: '/pages/index/index' });
      }
    });
  },

  scrollTop() {
    try {
      wx.pageScrollTo({ scrollTop: 0, duration: 0 });
    } catch (e) {
      /* ignore */
    }
  },

  /** grid → 进入某城市的计划列表 */
  onPick(e: WechatMiniprogram.TouchEvent) {
    const idx = Number(e.currentTarget.dataset.index);
    const d = this.data.list[idx];
    if (!d) return;
    this.setData({ curDest: d, view: 'plans' });
    this.scrollTop();
  },

  /** plans → 进入某计划对应的帖子 */
  onPickPlan(e: WechatMiniprogram.TouchEvent) {
    const idx = Number(e.currentTarget.dataset.index);
    const d = this.data.curDest;
    if (!d || !d.plans[idx]) return;
    this.setData({ curPlan: d.plans[idx], view: 'post' });
    this.scrollTop();
  },

  /** 以当前城市为目的地，一键创建行程（trip-edit 已支持新建预填 destination） */
  onCreateFrom() {
    const d = this.data.curDest;
    if (!d) return;
    const q = `destination=${encodeURIComponent(d.name)}&formTitle=${encodeURIComponent(`${d.name}之旅`)}`;
    go(`/subpackages/travel/pages/trip-edit/trip-edit?${q}`, { title: '新建行程' });
  },

  onShareAppMessage(): WechatMiniprogram.Page.ICustomShareContent {
    return { title: '旅行灵感 · 想去哪儿？', path: '/subpackages/travel/pages/inspiration/inspiration' };
  }
});
