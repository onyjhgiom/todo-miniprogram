interface TravelPost {
  /** 帖子标题 */
  title: string;
  /** 导语 */
  lead: string;
  /** 正文段落 */
  body: string[];
  /** 详情：建议天数 / 最佳季节 / 参考预算 */
  days: number;
  bestSeason: string;
  budget: string;
  /** 亮点 */
  highlights: string[];
  /** 行程概要（每日一句） */
  outline: string[];
}

interface TravelPlan {
  id: string;
  /** 计划标题，如「京都红叶古寺 5 日」 */
  title: string;
  /** 一句话简介 */
  summary: string;
  /** 计划标签 */
  tags: string[];
  /** 该计划对应的帖子 */
  post: TravelPost;
}

interface Dest {
  name: string;
  en: string;
  region: string;
  season: string;
  budget: string;
  blurb: string;
  tags: string[];
  img: string;
  /** 推荐旅行计划列表 */
  plans: TravelPlan[];
  /** 网格里用于渐变卡的大字（无实拍图时使用） */
  glyph?: string;
  /** 渐变主题（无实拍图时着色） */
  theme?: 'sun' | 'jade' | 'sea' | 'violet' | 'earth';
  /** 网格错落：特征卡更高，做视觉焦点 */
  feature?: boolean;
  /** 运行期注入的原始下标（onPick 回查 list 用） */
  index?: number;
}

