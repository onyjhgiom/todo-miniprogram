/** 由日期生成稳定种子（同日所有用户一致） */
function daySeed(d: Date): number {
  const y = d.getFullYear();
  const m = d.getMonth() + 1;
  const day = d.getDate();
  // 简单哈希，保证同日起始值稳定
  return (y * 372 + m * 31 + day) % 100000;
}

export interface DailyEntry {
  dateLabel: string;
  wuxing: DailyWuxing;
  fengwu: string;
  verse: DailyVerse;
}

/** 按日期生成当日国风雅集（纯函数，便于缓存与刷新） */
export function getDaily(d: Date = new Date()): DailyEntry {
  const seed = daySeed(d);
  const pad = (n: number) => (n < 10 ? '0' + n : '' + n);
  const dateLabel = `${d.getFullYear()}年${pad(d.getMonth() + 1)}月${pad(d.getDate())}日`;
  return {
    dateLabel,
    wuxing: WUXING[seed % WUXING.length],
    fengwu: FENGWU[seed % FENGWU.length],
    verse: VERSES[seed % VERSES.length]
  };
}

