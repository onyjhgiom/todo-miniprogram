/** 取赛道定义 */
export function trackOf(key: string): CivilTrack {
  return CIVIL_TRACKS.filter((t) => t.key === key)[0] || CIVIL_TRACKS[4];
}

/** 带岗位的四个赛道（不含策略中心） */
export const JOB_TRACKS: CivilTrack[] = CIVIL_TRACKS.filter((t) => t.key !== 'strategy');

/* ==================== 官方报名入口 ====================
 *
 * 【为什么是「入口」而不是「岗位直链」】
 *   本库的岗位是**泛化的示例岗**（「某省税务局」「某市公安局」这类），不是某年某条具体公告，
 *   因此不存在、也不该编造「某岗位专属报名链接」。能给、且必须给的是：
 *   该岗位**所属招录体系的官方报名入口**——用户点进去后在站内检索具体职位即可完成报名。
 *
 * 【收录标准（宁缺勿滥）】
 *   仅收录政府机关 / 部委 / 央企集团**自己主办**的平台，不收录任何商业招聘网站。
 *   每条 URL 都经过可达性验证，host 白名单由 scripts/check-civil-apply-link.js 强制守卫。
 */

export interface ApplyPortal {
  /** 入口全称（照抄官方站名，便于用户核对） */
  name: string;
  /** 官方 URL */
  url: string;
  /** 域名：单独展示，让用户一眼判断「是不是官方网站」 */
  host: string;
  /** 主办单位 */
  org: string;
  /** 怎么用：官方定位 + 抵达具体岗位的路径 */
  note: string;
  /** 入口短名：列表卡片空间有限，用它露出「去哪报名」 */
  short: string;
}

const PORTAL = (
  name: string, url: string, org: string, note: string, short: string
): ApplyPortal => {
  const m = /^(https?:\/\/)?([^/?#]+)/i.exec(url);
  return { name, url, host: m ? m[2] : '', org, note, short };
};

