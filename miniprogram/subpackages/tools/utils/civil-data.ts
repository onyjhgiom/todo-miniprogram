const COMPILE_MAP: Record<string, CompileType> = {};
COMPILE_TYPES.forEach((c) => {
  COMPILE_MAP[c.key] = c;
});

/** 取编制类型定义；未知 key 兜底为「合同制」 */
export function compileOf(key: string): CompileType {
  return COMPILE_MAP[key] || COMPILE_MAP.contract;
}

