/* ==================== 渲染辅助 ==================== */

/** #RRGGBB + alpha → rgba() 字符串（标签底色用；避免 8 位 hex 在旧 WebView 不生效） */
export function hexA(hex: string, a: number): string {
  const h = String(hex || '').replace('#', '');
  const full = h.length === 3 ? h.split('').map((c) => c + c).join('') : h;
  const n = parseInt(full, 16);
  if (!isFinite(n) || full.length !== 6) return `rgba(120, 120, 120, ${a})`;
  return `rgba(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}, ${a})`;
}

/** 编制色调：bian=有编 / unbian=无编 / warn=慎选（页面据此上色，深浅色都能读） */
export function compileTone(key: string): 'bian' | 'unbian' | 'warn' {
  if (key === 'dispatch') return 'warn';
  if (key === 'contract' || key === 'soeMarket') return 'unbian';
  return 'bian';
}

/** 编制短语：一句话说清有没有编（列表页最关键的一行） */
export function compilePhrase(key: string): string {
  const c = compileOf(key);
  return c.hasBian ? `有编制 · ${c.short}` : `无编制 · ${c.short}`;
}

