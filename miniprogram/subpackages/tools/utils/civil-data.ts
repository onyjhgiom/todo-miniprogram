/**
 * 国考年度专题链接。
 *
 * 专题站按「招考年度」分址（bm.scs.gov.cn/kl2026 指 2026 年度），
 * 且**考前一年 10 月才开放**（2026 年 10 月开的是 2027 年度专题）。
 * 若在专题未开放时硬拼 kl{次年}，用户点开就是 404——所以这里按时段给不同地址。
 */
export function gkApplyPortal(now: number = Date.now()): ApplyPortal {
  const base = APPLY_PORTALS.gk;
  const d = new Date(now);
  const y = d.getFullYear();
  const opened = d.getMonth() + 1 >= 10; // 10 月起本年度（次年招考年度）专题已开放
  const year = opened ? y + 1 : y + 1;   // 2026 年 10 月 → 2027 年度
  if (opened) {
    return Object.assign({}, base, {
      url: `http://bm.scs.gov.cn/kl${year}`,
      short: `${year} 年度专题`,
      note: `${year} 年度专题已开放：本页即为报名入口，用「招考简章」检索职位后提交报考申请。`
    });
  }
  return Object.assign({}, base, {
    url: base.url,
    note:
      `${year} 年度专题预计 ${y} 年 10 月中旬开放，届时报名网址为 bm.scs.gov.cn/kl${year}；` +
      `当前请先访问本页（专题站根域）查看最新公告与开放状态。`
  });
}

