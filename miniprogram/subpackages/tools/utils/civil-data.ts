export interface JobFilter {
  track?: string;
  compile?: string;
  keyword?: string;
  /** 只看带编 */
  bianOnly?: boolean;
  /** 只看应届可报 */
  freshOnly?: boolean;
  /** 学历筛选：专科 / 本科 / 硕士 */
  education?: string;
}

const EDU_RANK: Record<string, number> = { '专科及以上': 1, '本科及以上': 2, '硕士及以上': 3 };

/** 岗位筛选（行业/编制/关键词/带编/应届/学历） */
export function filterJobs(f: JobFilter): CivilJob[] {
  const kw = (f.keyword || '').trim().toLowerCase();
  return CIVIL_JOBS.filter((j) => {
    if (f.track && f.track !== 'all' && j.track !== f.track) return false;
    if (f.compile && f.compile !== 'all' && j.compile !== f.compile) return false;
    if (f.bianOnly && !compileOf(j.compile).hasBian) return false;
    if (f.freshOnly && j.fresh === 'no') return false;
    if (f.education && f.education !== 'all') {
      const want = EDU_RANK[f.education] || 0;
      const got = EDU_RANK[j.education] || 0;
      // 岗位学历要求 ≤ 用户学历 才算可报
      if (want && got > want) return false;
    }
    if (kw) {
      const hay = `${j.title} ${j.unit} ${j.direction} ${j.majorLimit} ${j.industry} ${j.region} ${j.level}`.toLowerCase();
      if (hay.indexOf(kw) < 0) return false;
    }
    return true;
  });
}

