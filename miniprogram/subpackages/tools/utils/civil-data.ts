/** 把矩阵模板展开成与时序种子同构的 JobSeed 组（按赛道分组，前缀避免与 gk/sk/sy/yg 冲突） */
function buildMatrixSeeds(): { track: JobTrack; seeds: JobSeed[]; prefix: string }[] {
  const groups: Record<string, { track: JobTrack; seeds: JobSeed[]; prefix: string }> = {
    gkm: { track: 'gk', prefix: 'gkm', seeds: [] },
    skm: { track: 'sk', prefix: 'skm', seeds: [] },
    sym: { track: 'sy', prefix: 'sym', seeds: [] },
    ygm: { track: 'yg', prefix: 'ygm', seeds: [] }
  };
  MATRIX_TEMPLATES.forEach((t) => {
    const g = groups[`${t.track}m`];
    const applyTime = t.applyTime || MATRIX_APPLY[t.track];
    const examTime = t.examTime || (t.track === 'sy' && t.industry === '医疗' ? '医院自定' : MATRIX_EXAM[t.track]);
    t.dirs.forEach((d) => {
      g.seeds.push([
        d.title, t.unit, t.region, t.level, t.compile, t.industry, d.dir, d.major,
        d.edu || t.education, t.fresh, t.party, applyTime, examTime, t.ratio,
        d.diff || t.difficulty, d.sal || t.salary
      ] as JobSeed);
    });
  });
  return [groups.gkm, groups.skm, groups.sym, groups.ygm];
}

