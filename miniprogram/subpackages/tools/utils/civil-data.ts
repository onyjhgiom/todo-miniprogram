/**
 * 为岗位挑选官方报名入口。
 *
 * 判定优先级：招录体系 > 用工形式。
 * 原则是「能落到专属官方渠道就落专属，落不了就落该体系的权威平台」，
 * 例如电网岗位直接给国网招聘平台（官方公告明确为唯一渠道），
 * 而各集团自行组织的央企校招则落到国资委的国资央企招聘平台。
 */
function portalFor(track: JobTrack, s: JobSeed, now: number): ApplyPortal {
  const compile = s[4];
  const industry = s[5];
  const level = s[3];
  const examTime = s[12];

  if (track === 'gk') return gkApplyPortal(now);
  if (track === 'sk') return APPLY_PORTALS.sk;

  if (track === 'sy') {
    // 「各校自定 / 医院自定 / 院自定 / 集团自定」= 用人单位自主招聘，不走统考
    if (examTime.indexOf('自定') >= 0) return APPLY_PORTALS.sySelf;
    return APPLY_PORTALS.syUnion;
  }

  // 央国企
  if (industry === '能源电力') return APPLY_PORTALS.ygSgcc;      // 电网走国网招聘平台（唯一官方渠道）
  if (compile === 'dispatch') return APPLY_PORTALS.ygLocal;      // 劳务派遣多由地方单位自行发布
  if (compile === 'soeMarket') return APPLY_PORTALS.ygGuopin;    // 市场化用工集中在国聘行动
  if (level === '省属国企' || level === '市属国企') return APPLY_PORTALS.ygLocal; // 地方国企走公共招聘网
  return APPLY_PORTALS.ygSasac;                                   // 央企正式工走国资委平台
}

/**
 * 生成本岗位的「入口内检索路径」。
 *
 * 为什么需要它：入口是体系级的（如国考专题站），同一入口下挂着成百上千个职位。
 * 只给入口不给路径，用户点进去仍然不知道哪一条是自己看的这个岗；
 * 而编造「某岗位专属直链」是绝对禁止的（这些岗位是泛化示例岗，不存在专属链接）。
 * 折中且诚实的做法：把该岗位自带的真实字段（职位名/方向/行业/地区/层级/单位）
 * 拼成一条站内检索式，粘进平台搜索框即可定位到对应职位。
 */
function pathFor(track: JobTrack, s: JobSeed): string {
  const title = s[0];
  const unit = s[1];
  const region = s[2];
  const level = s[3];
  const industry = s[5];
  const direction = s[6];
  const examTime = s[12];

  if (track === 'gk') {
    return `招考简章 → 按「${direction}」检索 → 职位「${title}」（地区：${region}）`;
  }
  if (track === 'sk') {
    return `本省考录职位表 → 按「${title}」检索（层级：${level}｜地区：${region}）`;
  }
  if (track === 'sy') {
    if (examTime.indexOf('自定') >= 0) {
      return `按地区「${region}」+ 行业「${industry}」筛选 → 检索「${title}」`;
    }
    return `本省事业单位统考岗位表 → 按「${title}」检索（行业：${industry}）`;
  }
  if (industry === '能源电力') {
    return `招聘公告 → 选择「${unit}」→ 志愿填报（岗位：${title}）`;
  }
  return `检索单位「${unit}」→ 校招公告 → 岗位「${title}」（地区：${region}）`;
}

function expand(): CivilJob[] {
  const out: CivilJob[] = [];
  const now = Date.now();
  SEED_GROUPS.forEach((grp) => {
    grp.seeds.forEach((s, i) => {
      out.push({
        id: `${grp.prefix}${i + 1}`,
        title: s[0],
        unit: s[1],
        track: grp.track,
        region: s[2],
        level: s[3],
        compile: s[4] as CompileKey,
        industry: s[5],
        direction: s[6],
        majorLimit: s[7],
        education: s[8],
        fresh: s[9],
        party: s[10] === 1,
        applyTime: s[11],
        examTime: s[12],
        ratio: s[13],
        difficulty: s[14],
        salary: s[15],
        apply: portalFor(grp.track, s, now),
        applyPath: pathFor(grp.track, s)
      });
    });
  });
  return out;
}

