/* ==================== 基础类型 ==================== */

/** 赛道 key（strategy 不是岗位赛道，是通用策略中心） */
export type CivilTrackKey = 'gk' | 'sk' | 'sy' | 'yg' | 'strategy';
/** 真正带岗位的赛道 */
export type JobTrack = 'gk' | 'sk' | 'sy' | 'yg';
/** 应届生要求：only 仅限应届 / prefer 应届优先 / no 不限 */
export type Fresh = 'only' | 'prefer' | 'no';
/** 难度 1-5 */
export type Difficulty = 1 | 2 | 3 | 4 | 5;

/** 编制类型 key */
export type CompileKey =
  | 'admin' // 行政编制（公务员）
  | 'careerFull' // 全额拨款事业编
  | 'careerDiff' // 差额拨款事业编
  | 'careerSelf' // 自收自支事业编
  | 'record' // 备案制 / 员额制
  | 'contract' // 合同制（无编）
  | 'soeFormal' // 国企正式工（企业编）
  | 'soeMarket' // 国企市场化合同制
  | 'dispatch'; // 劳务派遣（事业单位 / 国企通用）

/* ==================== 编制类型（核心差异化） ==================== */

export interface CompileType {
  key: CompileKey;
  /** 全称，如「全额拨款事业编制」 */
  label: string;
  /** 短标签，列表用，如「全额事业编」 */
  short: string;
  /** 是否属于传统意义上的「有编制」 */
  hasBian: boolean;
  /** 稳定性档位 */
  level: 'stable' | 'semi' | 'unstable';
  /** 稳定性文字 */
  levelLabel: string;
  /** 一句话说明 */
  desc: string;
  /** 优势 */
  pros: string[];
  /** 劣势 / 注意 */
  cons: string[];
  /** 避雷提示（空串表示无） */
  warning: string;
  /** 标签主色 */
  color: string;
  /** 标签底色 */
  bg: string;
}

