const DIFFS = ['简单', '中等', '困难'];

function shuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); const t = a[i]; a[i] = a[j]; a[j] = t; }
  return a;
}

/** 归一化：全角转半角、去空白与标点、统一数字写法、去掉语气词 */
function normalize(s) {
  if (!s) return '';
  let t = String(s);
  // 全角转半角
  t = t.replace(/[\uFF01-\uFF5E]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0xFEE0));
  t = t.replace(/\u3000/g, ' ');
  // 去空白与常见标点（含引号书名号）
  t = t.replace(/[\s,.;:!?'"`~@#$%^&*()\[\]{}<>\-_+=\\/|、。，；：！？‘’“”《》（）【】「」·…—]/g, '');
  // 中文数字转阿拉伯
  const cn = { 一: '1', 二: '2', 两: '2', 三: '3', 四: '4', 五: '5', 六: '6', 七: '7', 八: '8', 九: '9', 十: '10' };
  t = t.replace(/[一二两三四五六七八九十]/g, (ch) => cn[ch] || ch);
  // 去掉常见语气词后缀
  t = t.replace(/(的话|的时候|啊|呀|吧|呢|了|嘛|哦)$/g, '');
  return t.toLowerCase();
}

/**
 * 判断用户输入是否正确。
 * 采用双向包含而非仅单向：既要容忍用户多写（「答案是水」含「水」），
 * 也要容忍用户少写（「尾巴朝下」vs 标准答案「朝下」）。
 * 但仅当较短一方长度 ≥ 2 时才允许「短包含于长」，避免单字答案（水 / 地）
 * 出现在无关长句中造成误判。
 */
function checkAnswer(input, item) {
  const v = normalize(input);
  if (!v) return false;
  const pool = [item.a].concat(item.acc || []);
  for (const p of pool) {
    const n = normalize(p);
    if (!n) continue;
    if (v === n) return true;
    if (v.indexOf(n) >= 0) return true;            // 用户多写了内容
    if (n.indexOf(v) >= 0 && v.length >= 2) return true; // 用户少写了内容（短答案除外）
  }
  return false;
}

